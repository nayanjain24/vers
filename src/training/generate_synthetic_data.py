def _normalise(landmarks: np.ndarray) -> np.ndarray:
    """Wrist-centre and scale-normalise."""
    v = landmarks.copy()
    v -= v[0]
    scale = np.max(np.abs(v))
    if scale > 1e-6:
        v /= scale
    return v.flatten()


def _generate_sequence(word: str, base_pose: np.ndarray, noise_scale: float = 0.02) -> np.ndarray:
    """Generate one 30-frame sequence with word-specific temporal dynamics."""
    frames = []
    for t in range(SEQUENCE_LENGTH):
        frame = base_pose.copy()
        
        # Invert Y axis so fingers pointing UP correspond to negative Y
        # (Matches real camera view where Y=0 is top of screen)
        frame[:, 1] = -frame[:, 1]
        
        # Small spatial jitter
        frame += np.random.randn(21, 3).astype(np.float32) * noise_scale
        
        # Word-specific temporal motions
        progress = t / SEQUENCE_LENGTH  # 0 to 1
        phase = 2 * np.pi * progress
        
        # We perform rotations relative to wrist (index 0)
        wrist = frame[0].copy()
        frame -= wrist
        
        if word == "HELLO":
            # Wave back and forth (Z-axis rotation / roll)
            angle = np.sin(phase * 3) * 0.5
            rot_z = np.array([[np.cos(angle), -np.sin(angle), 0],
                              [np.sin(angle),  np.cos(angle), 0],
                              [0, 0, 1]])
            frame = frame @ rot_z.T
            
        elif word == "NO":
            # Wagging index finger (landmarks 5-8)
            angle = np.sin(phase * 4) * 0.4
            rot_z = np.array([[np.cos(angle), -np.sin(angle), 0],
                              [np.sin(angle),  np.cos(angle), 0],
                              [0, 0, 1]])
            idx_base = frame[5].copy()
            for i in range(5, 9):
                frame[i] = (frame[i] - idx_base) @ rot_z.T + idx_base
                
        elif word == "WHERE":
            # Circling index finger
            angle_x = np.cos(phase * 2) * 0.3
            angle_y = np.sin(phase * 2) * 0.3
            for i in range(5, 9):
                frame[i, 0] += angle_x * (i-4)*0.1
                frame[i, 1] += angle_y * (i-4)*0.1
                
        elif word == "UNDERSTAND":
            # Flick index finger up
            if progress < 0.5:
                # Curl index finger down
                frame[6:9, 1] += 0.2
                frame[6:9, 2] -= 0.1
                
        elif word == "FINISHED":
            # Shake open palms (Y-axis rotation / twist)
            angle = np.sin(phase * 3) * 0.6
            rot_y = np.array([[np.cos(angle), 0, np.sin(angle)],
                              [0, 1, 0],
                              [-np.sin(angle), 0, np.cos(angle)]])
            frame = frame @ rot_y.T
            
        elif word == "FALL":
            # Pitch hand down (X-axis rotation)
            angle = min(progress * 1.5, 1.5)
            rot_x = np.array([[1, 0, 0],
                              [0, np.cos(angle), -np.sin(angle)],
                              [0, np.sin(angle),  np.cos(angle)]])
            frame = frame @ rot_x.T
            
        elif word in ["FAMILY", "SORRY", "PLEASE"]:
            # Circular motion
            angle_p = np.cos(phase * 2) * 0.2
            angle_y = np.sin(phase * 2) * 0.2
            rot_x = np.array([[1, 0, 0], [0, np.cos(angle_p), -np.sin(angle_p)], [0, np.sin(angle_p), np.cos(angle_p)]])
            rot_y = np.array([[np.cos(angle_y), 0, np.sin(angle_y)], [0, 1, 0], [-np.sin(angle_y), 0, np.cos(angle_y)]])
            frame = frame @ rot_x.T @ rot_y.T
            
        elif word == "DANGER":
            # Rotated wrist
            angle = np.sin(phase * 2) * 0.5
            rot_z = np.array([[np.cos(angle), -np.sin(angle), 0],
                              [np.sin(angle),  np.cos(angle), 0],
                              [0, 0, 1]])
            frame = frame @ rot_z.T
            
        elif word == "BAD":
            # Turn palm down
            angle = min(progress * 2.0, 3.14)
            rot_x = np.array([[1, 0, 0], [0, np.cos(angle), -np.sin(angle)], [0, np.sin(angle), np.cos(angle)]])
            frame = frame @ rot_x.T
            
        elif word == "WANT":
            # Pulling towards body (curl fingers slightly)
            curl = progress * 0.3
            for i in [6,7,8, 10,11,12, 14,15,16, 18,19,20]:
                frame[i, 1] += curl
                frame[i, 2] -= curl
                
        elif word == "MORE":
            # Tapping fingertips together
            tap = np.abs(np.sin(phase * 3)) * 0.2
            frame[:, 0] -= np.sign(frame[:, 0]) * tap
            
        elif word == "NAME":
            # Tap index & middle
            tap = np.abs(np.sin(phase * 4)) * 0.1
            frame[5:9, 0] += tap
            frame[9:13, 0] -= tap
            
        elif word == "YES":
            # Nodding (pitch)
            angle = np.sin(phase * 3) * 0.4
            rot_x = np.array([[1, 0, 0], [0, np.cos(angle), -np.sin(angle)], [0, np.sin(angle), np.cos(angle)]])
            frame = frame @ rot_x.T
            
        else:
            # Gentle sway
            frame[:, 1] += np.sin(phase) * noise_scale * 0.5
            
        frame += wrist
        frames.append(_normalise(frame))
    return np.array(frames, dtype=np.float32)


def generate_all() -> None:
    """Generate training data for all 15 emergency words."""
    # Clear old data first
    if DATA_DIR.exists():
        shutil.rmtree(DATA_DIR)
    DATA_DIR.mkdir(parents=True, exist_ok=True)

    print("=" * 60)
    print("Generating Unique Synthetic Sign Language Data")
    print("=" * 60)

    total = 0
    for word in SIGN_VOCABULARY:
        if word == "NONE":
            continue

        base_pose = UNIQUE_POSES[word]
        word_dir = DATA_DIR / word
        word_dir.mkdir(parents=True, exist_ok=True)

        for i in range(SAMPLES_PER_WORD):
            seq = _generate_sequence(word, base_pose, noise_scale=0.02)
            np.save(word_dir / f"seq_{i:03d}.npy", seq)

        total += SAMPLES_PER_WORD
        print(f"  ✅ {word:12s} — {SAMPLES_PER_WORD} sequences")

    print(f"\nTotal: {total} sequences across {len(UNIQUE_POSES)} unique poses")
    print(f"Saved to: {DATA_DIR}")


if __name__ == "__main__":
    generate_all()
